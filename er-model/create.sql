-- FIELD_TASK
CREATE TABLE FIELD_TASK (
    TaskID INT IDENTITY(1,1) NOT NULL,
    TaskType VARCHAR(17) NOT NULL CONSTRAINT CK_FIELD_TASK_TaskType CHECK (TaskType IN ('Installation', 'Replacement', 'Technical check', 'Anti-tamper check')),
    ScheduledFrom DATETIME2(0) NOT NULL,
    ScheduledTo DATETIME2(0) NOT NULL,
    Status VARCHAR(9) NOT NULL CONSTRAINT DF_FIELD_TASK_Status DEFAULT 'Assigned' CONSTRAINT CK_FIELD_TASK_Status CHECK (Status IN ('Assigned', 'Accepted', 'Done', 'Cancelled')),
    Result NVARCHAR(1000) NULL,
    CreatedAt DATETIME2(0) NOT NULL CONSTRAINT DF_FIELD_TASK_CreatedAt DEFAULT SYSUTCDATETIME(),
    CompletedAt DATETIME2(0) NULL,
    TechnicianID INT NOT NULL,
    PremiseID INT NULL,
    MeterID INT NULL,
    RequestID INT NULL,
    CONSTRAINT PK_FIELD_TASK PRIMARY KEY (TaskID),
    CONSTRAINT FK_FIELD_TASK_ASSIGNED_TO FOREIGN KEY (TechnicianID) REFERENCES FIELD_TECHNICIAN (UserID),
    CONSTRAINT FK_FIELD_TASK_TASK_AT FOREIGN KEY (PremiseID) REFERENCES PREMISE (PremiseID),
    CONSTRAINT FK_FIELD_TASK_TASK_ON FOREIGN KEY (MeterID) REFERENCES METER (MeterID),
    CONSTRAINT FK_FIELD_TASK_RESOLVED_BY FOREIGN KEY (RequestID) REFERENCES SERVICE_REQUEST (RequestID),
    CONSTRAINT CK_FIELD_TASK_Schedule CHECK (ScheduledTo > ScheduledFrom),
    CONSTRAINT CK_FIELD_TASK_Done CHECK ((Status = 'Done' AND CompletedAt IS NOT NULL AND Result IS NOT NULL) OR (Status <> 'Done' AND CompletedAt IS NULL)),
    CONSTRAINT CK_FIELD_TASK_Target CHECK (PremiseID IS NOT NULL OR MeterID IS NOT NULL),
